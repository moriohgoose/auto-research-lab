import logging
from typing import List, Any, Optional


class ToolManager:
    """
    Manages a collection of tools available to the agent.

    Responsibilities:
    - Stores the set of active tools.
    - Provides information about available tools (names, instructions) for the agent's prompt.
    - Identifies the correct tool requested by the agent based on the query format.
    - Processes the agent's query to extract the input for the tool.
    - Executes the identified tool with the processed input.
    - Handles errors related to tool finding and execution.
    """
    def __init__(self, toolset: List):
        """
        Initializes the ToolManager with a list of tool instances.

        Args:
            toolset (List[Any]): A list containing instances of the tool classes
                                 (e.g., PubMedSearch, ClinicalTox, BBBPredictTool).
                                 Each tool instance is expected to have at least a
                                 'tool_call_name' attribute and relevant methods.
        """
        self.toolset = toolset
        # Verify uniqueness of tool_call_name to prevent ambiguity
        call_names = [t.tool_call_name for t in toolset if hasattr(t, 'tool_call_name')]
        if len(call_names) != len(set(call_names)):
            logging.error(f"ToolManager Initialization Error: Duplicate 'tool_call_name' detected among tools: {call_names}. This can lead to incorrect tool selection.")
        logging.info(f"ToolManager initialized with active tools (call names): {call_names}")

    def tool_prompt(self) -> str:
        """
        Generates the part of the agent's system prompt listing available tools
        and providing access to their instructions.

        Returns:
            str: A formatted string listing tool call names and referencing instructions.
        """
        # Get the unique call names for the prompt
        tool_call_names = ", ".join(sorted([t.tool_call_name for t in self.toolset if hasattr(t, 'tool_call_name')]))
        if not tool_call_names:
             return "No tools available."
        # Combine names with a reference to the full instructions provided separately
        return f"Available Tools: {tool_call_names}\n{self.tool_instructions()}\nYou MUST use ONE tool per action."

    def tool_instructions(self) -> str:
        """
        Generates a consolidated string containing the specific instructions
        for each available tool.

        Returns:
            str: A multi-line string with instructions for all tools.
        """
        # Collect instructions from all tools that provide them
        instruction_list = [t.instructions() for t in self.toolset if hasattr(t, 'instructions')]
        return "\n\n".join(instruction_list) # Separate instructions for clarity


    def use_tool(self, agent_query: str) -> str:
        """
        Identifies the requested tool from the agent's query, processes the input,
        executes the tool, and returns the result or an error message.

        Args:
            agent_query (str): The raw action string generated by the agent, expected
                               to contain a tool call block (e.g., ```ToolName\nInput```).

        Returns:
            str: The result from the executed tool or a descriptive error message.
        """
        if not agent_query or not isinstance(agent_query, str):
            logging.warning("ToolManager.use_tool received an invalid query.")
            return "Error: Invalid query format received by ToolManager."

        logging.info(f"ToolManager attempting to find tool for query (start): '{agent_query[:100]}...'")
        logging.debug(f"Full agent query: {agent_query}")

        tool_found = False
        selected_tool = None

        # Iterate through available tools to find a match based on the call name format
        for tool in self.toolset:
            # Check if the tool has the necessary attributes and if the query matches its activation pattern
            if hasattr(tool, 'tool_call_name') and hasattr(tool, 'tool_is_used') and tool.tool_is_used(agent_query):
                tool_found = True
                selected_tool = tool
                logging.info(f"Tool identified: {selected_tool.tool_call_name} (Call name: {selected_tool.tool_call_name})")
                break # Stop searching once a tool is found

        if not tool_found or selected_tool is None:
            logging.warning(f"No matching tool found for query: {agent_query}")
            # Provide a helpful error message listing available *call names*
            available_call_names = [t.tool_call_name for t in self.toolset if hasattr(t, 'tool_call_name')]
            return f"Error: Tool call not recognized. Available tools: {available_call_names}. Ensure format ```ToolName\\nInput\\n``` is used."

        # Process the query to extract the specific input for the selected tool
        if hasattr(selected_tool, 'process_query'):
            tool_input = selected_tool.process_query(agent_query)
            logging.debug(f"Input extracted for {selected_tool.tool_call_name}: '{tool_input}' (Type: {type(tool_input)})")
        else:
            logging.error(f"Tool {selected_tool.tool_call_name} is missing the 'process_query' method!")
            return f"Error: Internal configuration error for tool {selected_tool.tool_call_name}."

        # Validate the extracted input
        # (process_query might return None or specific types depending on the tool)
        if tool_input is None or (isinstance(tool_input, str) and not tool_input.strip()):
             logging.warning(f"Tool {selected_tool.tool_call_name} received empty or invalid input after processing query.")
             # Provide tool-specific input format hint if possible
             input_format_hint = getattr(selected_tool, 'instructions', lambda: "Check tool instructions.")()
             return f"Error: Invalid or empty input provided for {selected_tool.tool_call_name}. Expected format details:\n{input_format_hint}"

        # Execute the tool's main function
        try:
            if hasattr(selected_tool, 'use_tool'):
                tool_result = selected_tool.use_tool(tool_input)
                logging.debug(f"Result from {selected_tool.tool_call_name}: '{str(tool_result)[:100]}...'")
                return tool_result
            else:
                 logging.error(f"Tool {selected_tool.tool_call_name} is missing the 'use_tool' method!")
                 return f"Error: Internal configuration error for tool {selected_tool.tool_call_name}."
        except Exception as e:
            logging.error(f"Error during execution of {selected_tool.tool_call_name}: {e}", exc_info=True)
            return f"Error: An exception occurred while executing tool {selected_tool.tool_call_name}."
