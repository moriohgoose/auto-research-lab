import logging
import re
from typing import List, Dict, Optional
from Bio import Entrez, Medline
from utils.text_parser import extract_prompt

class PubMedSearch:
    """
    A tool for the agent to search the PubMed database using the NCBI Entrez API.

    It takes a search query string, searches PubMed, fetches metadata (including
    titles and abstracts) for the top relevant articles, and returns a formatted
    summary string.
    """
    def __init__(self, email):
        """
        Initializes the PubMedSearch tool.

        Args:
            email (str): A valid email address required by NCBI for using the Entrez API.
                         Using a default or invalid email may lead to blocked requests.
        """
        self.tool_call_name = "PubMedSearch" # Name used by the agent to call this tool
        self.tool_name = "PubMed Search"     # Human-readable name for logging
        Entrez.email = email                 # Set the email for all Entrez requests
        if not email or "@" not in email or "." not in email:
            logging.warning(f"PubMedSearch initialized with potentially invalid email: '{email}'. "
                            "NCBI Entrez API requires a valid email for reliable access.")
        elif email == "default_email@example.com":
             logging.warning("PubMedSearch: Please provide your real email address for Entrez API usage to avoid potential blocking.")
        logging.info(f"{self.tool_name} initialized.")

    def tool_is_used(self, query: str) -> bool:
        """
        Checks if the agent's query indicates an intent to use this specific tool.

        Args:
            query (str): The raw query string generated by the agent LLM.

        Returns:
            bool: True if the query format matches this tool's call sign, False otherwise.
        """
        # Checks for the specific tool call format (e.g., ```PubMedSearch...)
        return f"```{self.tool_call_name}" in query

    def process_query(self, query: str) -> str:
        """
        Extracts the actual search terms from the agent's formatted query.

        Args:
            query (str): The raw query string including the tool call block.

        Returns:
            str: The extracted search query string, stripped of formatting.
        """
        # Uses the utility function to get content within the ```ToolName ... ``` block
        search_text = extract_prompt(query, self.tool_call_name)
        return search_text.strip()

    def use_tool(self, search_text: str) -> str:
        """
        Performs the PubMed search using the Entrez API and formats the results.

        Args:
            search_text (str): The cleaned search query to send to PubMed.

        Returns:
            str: A formatted string containing the search results (titles of top articles)
                 or an error message if the search fails.
        """
        if not search_text:
            return "Error: Empty search query provided for PubMed."

        logging.info(f"Executing PubMed search for: '{search_text}'")
        max_results = 5 
        abstract_char_limit = 300

        try:
            # 1. Search for PMIDs
            search_handle = Entrez.esearch(db="pubmed",
                                          sort="relevance",
                                          term=search_text,
                                          retmax=str(max_results))
            search_record = Entrez.read(search_handle)
            pmids: List[str] = search_record.get("IdList", [])
            search_handle.close()

            if not pmids:
                logging.warning(f"PubMed search for '{search_text}' returned no results.")
                return f"PubMed: No articles found for query '{search_text}'. Please try a different or broader query."

            # 2. Fetch article details (Medline records) for the found PMIDs
            logging.debug(f"Fetching details for PMIDs: {pmids}")
            fetch_handle = Entrez.efetch(db="pubmed",
                                         id=",".join(pmids),
                                         rettype="medline",
                                         retmode="text")
            medline_records = list(Medline.parse(fetch_handle)) # Use list to consume iterator
            fetch_handle.close()

            if not medline_records:
                 logging.warning(f"Could not fetch Medline records for PMIDs: {pmids}")
                 return f"PubMed: Found PMIDs but failed to fetch details for '{search_text}'."

            # 3. Format the results string
            result_lines = [f"PubMed Search Results for '{search_text}':"]
            articles_added = 0
            for i, record in enumerate(medline_records):
                pmid = record.get("PMID", "N/A")
                title = record.get("TI", "No Title Available")
                abstract = record.get("AB", "")
                abstract_snippet = (abstract[:abstract_char_limit] + "..." if len(abstract) > abstract_char_limit else abstract) if abstract else "No Abstract"
                result_lines.append(f" {i+1}. [PMID:{pmid}] {title} (Abstract: {abstract_snippet})")
                result_lines.append(f" {i+1}. [PMID:{pmid}] {title}") 
                articles_added += 1

            if articles_added == 0:
                # Should not happen if medline_records is not empty, but as a safeguard
                return f"PubMed: Found PMIDs but could not extract details for '{search_text}'."

            logging.info(f"PubMed search successful for '{search_text}', returning {articles_added} results.")
            return "\n".join(result_lines)

        except Exception as e:
            # Catch potential network errors, API issues, or parsing problems
            logging.error(f"Error during PubMed search or processing for '{search_text}': {e}", exc_info=True)
            return f"Error: An issue occurred during PubMed search: {e}"

    def instructions(self) -> str:
        """
        Provides instructions for the orchestrator LLM on how to use this tool.
        """
        # Uses self.tool_call_name to ensure consistency
        return (
            f"=== {self.tool_name} ({self.tool_call_name}) ===\n"
            f"Searches the PubMed database for scientific articles based on a query.\n"
            f"Use relevant keywords (e.g., disease name, drug name, mechanism, gene).\n"
            f"Format: ```{self.tool_call_name}\n<search query terms here>\n```\n"
            f"Returns: A list of titles and PMIDs for the top relevant articles found."
        )