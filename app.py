"""
This is the main Streamlit application script.

It provides a user interface for generating scientific literature reviews and
research hypotheses with experimental plans using various AI models and services.
The application handles environment variable loading, API key configuration,
proxy settings, and displays dynamic content based on user selections.
"""

import streamlit as st
import os
import re
import sys
import time
import json
import logging
from dotenv import load_dotenv

# --- Add the project root to sys.path ---
project_root_dir = os.path.dirname(os.path.abspath(__file__))
if project_root_dir not in sys.path:
    sys.path.insert(0, project_root_dir)

# --- Logging settings ---
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - [%(filename)s:%(lineno)d] - %(message)s',
    datefmt='%Y-%m-%d %H:%M:%S',
    encoding='utf-8',
    handlers=[
        logging.StreamHandler(sys.stdout)
    ]
)
logger = logging.getLogger(__name__)

# --- Import UI Utility Functions ---
try:
    from utils.ui_utils import display_review_form, display_hypothesis_form, make_citations_clickable
except ImportError as e:
    st.error(f"Critical Error: Could not import UI utility functions from ui_utils.py: {e}")
    logger.critical(f"Failed to import from ui_utils.py: {e}", exc_info=True)
    st.stop()

# --- Loading environment variables ---
load_dotenv()
logger.info("Loaded environment variables for Streamlit app.")

# --- Proxy settings ---
proxy_host = os.getenv("PROXY_HOST")
proxy_port = os.getenv("PROXY_PORT")
proxy_user = os.getenv("PROXY_USER")
proxy_password = os.getenv("PROXY_PASSWORD")
use_proxy = all([proxy_host, proxy_port, proxy_user, proxy_password])

if use_proxy:
    # Constructs the proxy URLs and sets them as environment variables.
    proxies = {
        "http": f"http://{proxy_user}:{proxy_password}@{proxy_host}:{proxy_port}",
        "https": f"http://{proxy_user}:{proxy_password}@{proxy_host}:{proxy_port}",
    }
    os.environ["HTTP_PROXY"] = proxies["http"]
    os.environ["HTTPS_PROXY"] = proxies["https"]
    logger.info(f"HTTP_PROXY and HTTPS_PROXY set to: {proxies['http']}")
else:
    # If proxy settings are incomplete, ensure no proxy environment variables are set.
    logger.info("Proxy environment variables not fully set. Proceeding without proxy.")
    os.environ.pop("HTTP_PROXY", None)
    os.environ.pop("HTTPS_PROXY", None)

# --- API keys ---

# Configures the Google Gemini API
gemini_api_key = os.getenv("GOOGLE_API_KEY")
hf_token = os.getenv("HF_TOKEN")
pubmed_email = os.getenv("MY_EMAIL_FOR_PUBMED")

if not gemini_api_key:
    st.error("Ошибка: GOOGLE_API_KEY не найден в .env файле.")
    st.stop()
try:
    import google.generativeai as genai
    genai.configure(api_key=gemini_api_key)
    logger.info("Gemini API configured for Streamlit app.")
except Exception as e:
    st.error(f"Ошибка конфигурации Gemini API: {e}")
    st.stop()

# Hugging Face token
if not hf_token:
    logger.warning("HF_TOKEN не найден. Загрузка защищенных моделей Hugging Face может не удаться.")
else:
    os.environ["HF_TOKEN"] = hf_token
    logger.info("HF_TOKEN found.")

# PubMed email
if not pubmed_email:
    logger.warning("MY_EMAIL_FOR_PUBMED не найден. Это необходимо для режима генерации гипотез.")
else:
    os.environ["MY_EMAIL_FOR_PUBMED"] = pubmed_email
    logger.info("MY_EMAIL_FOR_PUBMED found.")


# --- Streamlit page settings ---
st.set_page_config(
    page_title="Auto Research Lab",
    page_icon="🔬",
    layout="wide",
    initial_sidebar_state="expanded"
)

# Displays the main title and a descriptive markdown text.
st.title("🔬 Auto Research Lab: AI for Scientific Discovery")
st.markdown("Automate your research workflows. Try one to get started:")

# --- Session State Initialization ---
# Initializes Streamlit's session state variables
if 'selected_mode' not in st.session_state:
    st.session_state.selected_mode = None # Stores the currently selected operational mode (e.g., "review", "hypothesis")
if 'running' not in st.session_state:
    st.session_state.running = False      # A flag indicating if a process is currently running
if 'results' not in st.session_state:
    st.session_state.results = None       # Stores the final results generated by the selected research process
if 'output_pdf_path' not in st.session_state:
    st.session_state.output_pdf_path = None # Stores the file path to the generated PDF report
if 'output_json_path' not in st.session_state:
    st.session_state.output_json_path = None # Stores the file path to the generated JSON data



# --- Select mode ---
# Creates two columns for displaying mode selection buttons
cols = st.columns(2)
with cols[0]:
    # Button to select "Generate Literature Review" mode
    if st.button("📝 Generate Literature Review", use_container_width=True, key="mode_review_btn"):
        st.session_state.selected_mode = "review" # Sets the mode
        st.session_state.results = None           # Clears previous results
        st.session_state.output_pdf_path = None   # Clears previous PDF path
        st.session_state.output_json_path = None  # Clears previous JSON path
        st.rerun() # Reruns the script to reflect the mode change and display the appropriate form

with cols[1]:
    # Button to select "Generate Hypothesis & Plan" mode
    if st.button("💡 Generate Hypothesis & Plan", use_container_width=True, key="mode_hyp_btn"):
        st.session_state.selected_mode = "hypothesis"
        st.session_state.results = None
        st.session_state.output_pdf_path = None
        st.session_state.output_json_path = None
        st.rerun()

st.markdown("---")

# --- Display form based on selected mode ---
if st.session_state.selected_mode == "review":
    # Calls a function from ui_utils.py to display the literature review input form
    display_review_form()
elif st.session_state.selected_mode == "hypothesis":
    # Calls a function from ui_utils.py to display the hypothesis generation input form
    display_hypothesis_form()
elif st.session_state.selected_mode is None:
    # Informational message if no mode has been selected yet 
    st.info("Please select a mode above to begin.")

# --- Results Display Section ---
# This section handles the display of generated results once a process has completed
if st.session_state.results:
    st.markdown("---") 
    final_data = st.session_state.results # results from session state
    results_header = "📄 Review" # header

    # Dynamically sets the results header based on the selected mode and available data
    if st.session_state.selected_mode == "review" and not final_data.get("error"):
        review_title = final_data.get('title')
        if review_title:
            results_header = f"📄 {review_title}"
    elif st.session_state.selected_mode == "hypothesis" and not final_data.get("error"):
        hypothesis_topic = final_data.get('research_topic', 'Hypothesis & Plan')
        results_header = f"💡 {hypothesis_topic}"

    st.subheader(results_header)

    # Checks if the results contain an error message
    if final_data.get("error"):
        st.error(f"Pipeline Error: {final_data.get('error')}")
    else:
        # Displaying results specific to the "review" mode
        if st.session_state.selected_mode == "review":

            # Retrieves ordered list of ArXiv URLs, used for making citations clickable    
            arxiv_urls_ordered = final_data.get("best_run_arxiv_ids", [])
            
            st.markdown(f"**Abstract:**")
            abstract_text_with_numbers = final_data.get('abstract', 'N/A') 

            # Converts numerical citations in the abstract into clickable links
            clickable_abstract = make_citations_clickable(abstract_text_with_numbers, arxiv_urls_ordered)
            st.markdown(clickable_abstract, unsafe_allow_html=True) # displays the abstract
            
            # Retrieves structured review sections
            review_sections_data_with_numbers = final_data.get("final_review_sections") 

            if review_sections_data_with_numbers and isinstance(review_sections_data_with_numbers, dict):
                
                section_order = [
                    "introduction", "key_themes", "methods_technologies",
                    "resources_datasets", "challenges_limitations",
                    "proposed_pipeline", "conclusion"
                ]
                processed_keys = set()

                # Iterates through the predefined order to display sections
                for section_key in section_order:
                    if section_key in review_sections_data_with_numbers:
                        section_content_with_numbers = review_sections_data_with_numbers[section_key]
                        display_title = section_key.replace('_', ' ').title() # Formats key as a title
                        st.markdown(f"### {display_title}")

                        # Makes citations within the section content clickable
                        clickable_section_content = make_citations_clickable(section_content_with_numbers, arxiv_urls_ordered)
                        if isinstance(clickable_section_content, str):
                            st.markdown(clickable_section_content, unsafe_allow_html=True)
                        else:
                            # Fallback if make_citations_clickable returns something unexpected
                            st.markdown(str(section_content_with_numbers), unsafe_allow_html=True)
                        processed_keys.add(section_key) # Marks the section as processed
                
                # Displays any remaining sections not covered by the `section_order`
                for section_key, section_content_with_numbers in review_sections_data_with_numbers.items():
                    if section_key not in processed_keys:
                        display_title = section_key.replace('_', ' ').title()
                        st.markdown(f"### {display_title} (Other)")
                        clickable_section_content = make_citations_clickable(section_content_with_numbers, arxiv_urls_ordered)
                        if isinstance(clickable_section_content, str):
                            st.markdown(clickable_section_content, unsafe_allow_html=True)
                        else:
                            st.markdown(str(section_content_with_numbers), unsafe_allow_html=True)

            # Fallback for displaying the entire review text if structured sections are not available
            elif final_data.get("final_literature_review_text"):
                st.markdown("**Generated Review Text (Fallback):**")
                fallback_text_raw = final_data.get("final_literature_review_text")
                clickable_fallback_text = make_citations_clickable(fallback_text_raw, arxiv_urls_ordered)
                st.markdown(clickable_fallback_text, unsafe_allow_html=True)
            else:
                st.warning("No review sections or fallback review text found.")

            # Displays formatted references
            formatted_references = final_data.get("references_formatted") 
            if formatted_references and isinstance(formatted_references, list):
                st.markdown("---")
                st.markdown("### References")
                display_references_markdown = []
                for i, ref_text_from_pipeline in enumerate(formatted_references):
                    numbered_ref_text = ref_text_from_pipeline

                   # Ensures references are numbered
                    if not re.match(r"^\s*\d+\.\s+", ref_text_from_pipeline):
                         numbered_ref_text = f"{i+1}. {ref_text_from_pipeline}"
                    else:
                         numbered_ref_text = ref_text_from_pipeline
                    display_references_markdown.append(numbered_ref_text)
                st.markdown("\n\n".join(display_references_markdown), unsafe_allow_html=True)

            # Fallback to display raw ArXiv URLs if formatted references are not available
            elif arxiv_urls_ordered: 
                st.markdown("---")
                st.markdown("### References (Raw URLs)")
                for i, url in enumerate(arxiv_urls_ordered):
                    arxiv_id_for_display = url.split('/')[-1]
                    st.markdown(f"{i+1}. [{arxiv_id_for_display}]({url})")
            else:
                st.markdown("---")
                st.markdown("### References")
                st.warning("No reference information available.")

        # Logic for displaying results specific to the "hypothesis" mode
        elif st.session_state.selected_mode == "hypothesis":
            response_text = final_data.get("final_agent_response", "No response generated.")
            
            st.markdown(response_text, unsafe_allow_html=True)

        # --- Download buttons ---
        # Provides options to download the generated report in PDF and JSON formats
        if st.session_state.output_pdf_path and os.path.exists(st.session_state.output_pdf_path):
            with open(st.session_state.output_pdf_path, "rb") as pdf_file:
                st.download_button(
                    label="Download PDF Report",
                    data=pdf_file,
                    file_name=os.path.basename(st.session_state.output_pdf_path),
                    mime="application/pdf"
                )
        if st.session_state.output_json_path and os.path.exists(st.session_state.output_json_path):
            with open(st.session_state.output_json_path, "rb") as json_file:
                st.download_button(
                    label="Download JSON Data",
                    data=json_file,
                    file_name=os.path.basename(st.session_state.output_json_path),
                    mime="application/json"
                )

st.markdown("---")
st.markdown("Auto Research Lab - Streamlit Interface")