import logging
import google.generativeai as genai
from typing import Optional
import config

ORCHESTRATOR_MODEL_NAME  = config.GEMINI_API_MODEL_NAME

def inference_gemini_orchestrator(prompt: str, system_prompt: Optional[str] = None) -> str:
    """
    Calls the configured Google Gemini API to get the agent's next thought,
    action, or final answer.

    This function acts as the "brain" or orchestrator for the agent, interpreting
    the current state (via the prompt and history) and deciding the next step
    or formulating the response.

    Args:
        prompt: The main user prompt or the constructed prompt including history
                for the current step.
        system_prompt: System instructions defining the agent's role and constraints
                       for the current step (optional, prepended to the main prompt).

    Returns:
        The text response generated by the Gemini model, or an error message
        if the API call fails or the response is blocked/malformed.
    """
    logging.debug(f"Calling Gemini API with model: {ORCHESTRATOR_MODEL_NAME}")
    logging.debug(f"  System Prompt (start): {system_prompt[:100] + '...' if system_prompt and len(system_prompt) > 100 else system_prompt}")
    logging.debug(f"  User Prompt (start): {prompt[:150] + '...' if len(prompt) > 150 else prompt}")

    try:
        model = genai.GenerativeModel(
            model_name=ORCHESTRATOR_MODEL_NAME
        )

        # Combine system prompt and user prompt if system prompt exists
        full_prompt = f"{system_prompt}\n\n{prompt}" if system_prompt else prompt

        # Send the request to the Gemini API
        response = model.generate_content(full_prompt)

        # Process the response, checking for potential issues
        if hasattr(response, 'text'):
            # Standard case: response has a direct text attribute
            logging.debug(f"  Gemini response received (start): {response.text[:150]}...")
            return response.text
        elif response.prompt_feedback and response.prompt_feedback.block_reason:
            # Case: Response was blocked by safety filters
            block_reason = response.prompt_feedback.block_reason
            logging.warning(f"Gemini response blocked due to: {block_reason}")
            # Return a clear error message indicating the block reason
            return f"Error: Response blocked by Gemini safety filters: {block_reason}"
        else:
            # Case: Response might be structured differently (e.g., using candidates/parts)
            # Attempt to extract text from the 'parts' attribute of the first candidate
            try:
                extracted_text = "".join(part.text for part in response.candidates[0].content.parts)
                logging.debug(f"  Gemini response extracted from 'parts' (start): {extracted_text[:150]}...")
                return extracted_text
            except (AttributeError, IndexError, Exception) as e_parts:
                # Log detailed error if extraction from parts fails
                logging.error(f"Could not extract text from Gemini response structure: {e_parts}. Full response object: {response}", exc_info=True)
                return "Error: Failed to get text from Gemini response (unknown structure)."

    except Exception as e:
        # Catch-all for other potential API errors (network issues, invalid key, etc.)
        logging.error(f"Critical error calling Gemini API ({ORCHESTRATOR_MODEL_NAME}): {e}", exc_info=True)
        # Include the original exception message for better diagnostics
        return f"Error: Critical failure during Gemini API call: {e}"