import logging
import time
from typing import Optional, List, Dict
import google.generativeai as genai

def generate_text(prompt: str, system_instruction: Optional[str] = None, model_name: str = "gemini-2.0-flash") -> Optional[str]:
    """
    Generates text using the specified Google Gemini model via its API.

    Includes basic retry logic and safety settings to minimize content blocking.

    Args:
        prompt (str): The main user prompt for the model.
        system_instruction (Optional[str]): System-level instructions to guide the model's behavior.
                                            This will be prepended to the user prompt.
        model_name (str): The specific Gemini model to use (e.g., "gemini-1.0-pro", "gemini-1.5-flash-latest").

    Returns:
        Optional[str]: The text generated by the model, or an error message string if generation fails
                       or content is blocked. Returns None if a critical API error occurs early.
    """
    logging.debug(f"Calling Gemini API with model: {model_name}")
    logging.info(f"Sending prompt to Gemini ({len(prompt)} chars): {prompt[:150]}...")
    max_retries = 2
    attempt = 0
    delay = 5

    while attempt < max_retries:
        attempt += 1
        try:
            model = genai.GenerativeModel(model_name) 
            response = model.generate_content(prompt)

            response_text = None
            try:
                 response_text = response.text
            except ValueError:
                 try:
                      if response.candidates:
                           candidate = response.candidates[0]
                           if candidate.content and candidate.content.parts:
                                response_text = "".join(part.text for part in candidate.content.parts if hasattr(part, 'text'))
                      else:
                           logging.error(f"  Gemini response has no text and no candidates. Response: {response}")
                 except (AttributeError, IndexError, Exception) as e_cand:
                      logging.error(f"  Error accessing candidates: {e_cand}. Original response: {response}")

            if response_text:
                logging.info(f"  Gemini API response received ({len(response_text)} chars): {response_text[:150]}...")
                return response_text
            else:
                 logging.warning(f"  Gemini API returned empty or blocked content (Attempt {attempt}/{max_retries}).")
                 return None

        except Exception as e:
            logging.error(f"  Gemini API error (Attempt {attempt}/{max_retries}): {e}")
            if attempt < max_retries:
                logging.info(f"  Retrying in {delay} seconds...")
                time.sleep(delay)
                delay *= 2
            else:
                logging.error("  Max retries reached after API errors.")
                return None
    return None
